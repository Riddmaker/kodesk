#!/usr/bin/env bash
# Refresh the hashed pip lock files used in CI (HABIT 1: no unverified downloads).
#
#   tools/lock-requirements.sh [--upgrade]
#
# Every *.in in data/packaging/ becomes a *.txt with exact versions and sha256 hashes for all
# platforms (universal), so `pip install -r` in CI runs in hash-checking mode.
set -euo pipefail
cd "$(dirname "$0")/.."
for source in data/packaging/*.in; do
    nix shell nixpkgs#uv -c uv pip compile "$@" --universal --python-version 3.13 \
        --generate-hashes --no-header --quiet "$source" -o "${source%.in}.txt"
    sed -i "1i # Generated by tools/lock-requirements.sh from $(basename "$source"); do not edit." \
        "${source%.in}.txt"
done
